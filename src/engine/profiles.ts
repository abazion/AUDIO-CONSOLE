export interface EqPresetRecommendation {
  primary: EqPresetItem;
  matchReason: string;
  alternates: EqPresetItem[];
  others: EqPresetItem[];
}

export function getRecommendedEqPresetsForChannel(channel: ChannelStrip): EqPresetRecommendation {
  const haystack = `${channel.name} ${channel.shortName} ${channel.micOrDiModel}`.toLowerCase();

  const scored = EQ_PRESETS.map((preset) => {
    let score = 0;
    const matchedTokens: string[] = [];

    for (const kw of preset.keywords) {
      if (haystack.includes(kw)) {
        score += kw.length >= 5 ? 12 : 8;
        matchedTokens.push(kw);
      }
    }
    if (preset.categories.includes(channel.category)) {
      score += 6;
    }

    return { preset, score, matchedTokens };
  }).sort((a, b) => b.score - a.score);

  const primaryEntry = scored[0];
  const primary = primaryEntry.preset;
  const alternates = scored.slice(1, 3).map((s) => s.preset);
  const others = scored.slice(3).map((s) => s.preset);

  const matchReason =
    primaryEntry.matchedTokens.length > 0
      ? `Matched "${channel.name}" (${primaryEntry.matchedTokens[0]}) · ${primary.summary}`
      : `Suggested for ${channel.category} · ${primary.summary}`;

  return {
    primary,
    matchReason,
    alternates,
    others,
  };
}

